"""Tiny S3 CLI for SeaweedFS (boto3), used from the host by the Makefile.

  python scripts/s3.py wait                      wait until the S3 API answers
  python scripts/s3.py mb BUCKET [BUCKET...]     create buckets (idempotent)
  python scripts/s3.py put LOCAL s3://b/key      upload a file
  python scripts/s3.py get s3://b/key LOCAL      download a file
  python scripts/s3.py put-dir DIR s3://b/pfx/   upload every file in DIR (non-recursive)
  python scripts/s3.py get-dir s3://b/pfx/ DIR   download every object under a prefix
  python scripts/s3.py ls [s3://b/pfx]           list buckets, or objects with size

Endpoint: $S3_ENDPOINT (default http://localhost:8333). Keys: $AWS_ACCESS_KEY_ID and
$AWS_SECRET_ACCESS_KEY, else read from .secrets/s3.env (generated by scripts/secrets.sh).
"""
import os
import sys
import time
from pathlib import Path

import boto3
from botocore.config import Config

ROOT = Path(__file__).resolve().parent.parent


def client():
    env_file = ROOT / ".secrets" / "s3.env"
    if "AWS_ACCESS_KEY_ID" not in os.environ and env_file.exists():
        for line in env_file.read_text().splitlines():
            if "=" in line:
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip())
    return boto3.client(
        "s3",
        endpoint_url=os.environ.get("S3_ENDPOINT", "http://localhost:8333"),
        region_name="us-east-1",
        config=Config(s3={"addressing_style": "path"}, retries={"max_attempts": 5}),
    )


def split(uri):
    assert uri.startswith("s3://"), uri
    bucket, _, key = uri[5:].partition("/")
    return bucket, key


def main(argv):
    if not argv:
        sys.exit(__doc__)
    cmd, args = argv[0], argv[1:]
    s3 = client()
    if cmd == "wait":
        for _ in range(90):
            try:
                s3.list_buckets()
                print("S3 API is up")
                return
            except Exception as exc:  # noqa: BLE001
                print(f"waiting for S3: {type(exc).__name__}")
                time.sleep(2)
        sys.exit("S3 API not reachable")
    elif cmd == "mb":
        have = {b["Name"] for b in s3.list_buckets().get("Buckets", [])}
        for b in args:
            if b not in have:
                s3.create_bucket(Bucket=b)
            print(f"bucket {b}: ok")
    elif cmd == "put":
        bucket, key = split(args[1])
        s3.upload_file(args[0], bucket, key)
        print(f"uploaded {args[0]} -> {args[1]}")
    elif cmd == "get":
        bucket, key = split(args[0])
        Path(args[1]).parent.mkdir(parents=True, exist_ok=True)
        s3.download_file(bucket, key, args[1])
        print(f"downloaded {args[0]} -> {args[1]}")
    elif cmd == "put-dir":
        bucket, prefix = split(args[1])
        for p in sorted(Path(args[0]).iterdir()):
            if p.is_file():
                s3.upload_file(str(p), bucket, prefix.rstrip("/") + "/" + p.name)
                print(f"uploaded {p} -> s3://{bucket}/{prefix.rstrip('/')}/{p.name}")
    elif cmd == "get-dir":
        bucket, prefix = split(args[0])
        prefix = prefix.rstrip("/") + "/"
        out = Path(args[1])
        out.mkdir(parents=True, exist_ok=True)
        for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket, Prefix=prefix):
            for o in page.get("Contents", []):
                rel = o["Key"][len(prefix):]
                if rel and "/" not in rel:
                    s3.download_file(bucket, o["Key"], str(out / rel))
                    print(f"downloaded s3://{bucket}/{o['Key']} -> {out / rel}")
    elif cmd == "ls":
        if not args:
            for b in s3.list_buckets().get("Buckets", []):
                print(f"bucket  {b['Name']}")
            return
        bucket, prefix = split(args[0])
        for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket, Prefix=prefix):
            for o in page.get("Contents", []):
                print(f"{o['Size']:>12}  s3://{bucket}/{o['Key']}")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
